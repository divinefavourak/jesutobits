// Draws the box-drawing logo (the banner in AGENTS.md) as SVGs of plain shapes, so it
// renders identically everywhere. As text, `█` and `═║╔╗╚╝` fall back to other fonts in
// many Markdown previews and lose their alignment.
// Outputs:
//   docs/assets/jesutobits-logo.svg  the full banner (README)
//   docs/assets/jesutobits-icon.svg  the "J" on a square tile, the source for the app icons
//                                    in the jesutobits-ide fork (ADR-0015)
// Run: node scripts/gen-logo.mjs
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ART = [
  "     ██╗███████╗███████╗██╗   ██╗████████╗ ██████╗ ██████╗ ██╗████████╗███████╗",
  "     ██║██╔════╝██╔════╝██║   ██║╚══██╔══╝██╔═══██╗██╔══██╗██║╚══██╔══╝██╔════╝",
  "     ██║█████╗  ███████╗██║   ██║   ██║   ██║   ██║██████╔╝██║   ██║   ███████╗",
  "██   ██║██╔══╝  ╚════██║██║   ██║   ██║   ██║   ██║██╔══██╗██║   ██║   ╚════██║",
  "╚█████╔╝███████╗███████║╚██████╔╝   ██║   ╚██████╔╝██████╔╝██║   ██║   ███████║",
  " ╚════╝ ╚══════╝╚══════╝ ╚═════╝    ╚═╝    ╚═════╝ ╚═════╝ ╚═╝   ╚═╝   ╚══════╝",
];
/** Columns of ART that hold the "J". */
const J_COLUMNS = 8;

// Terminal-like cell, twice as tall as wide. Double lines sit GAP_X / GAP_Y either side of
// the cell centre.
const W = 10;
const H = 20;
const GAP_X = 2;
const GAP_Y = 3;
const PAD = 10;

const GRADIENT_STOPS = `
      <stop offset="0" stop-color="#4F46E5"/>
      <stop offset="0.5" stop-color="#6366F1"/>
      <stop offset="1" stop-color="#9333EA"/>`;

/** Turns rows of box-drawing text into block rectangles and shadow line paths. */
function draw(art) {
  const blocks = [];
  const lines = [];

  art.forEach((line, row) => {
    const chars = [...line];
    const y0 = PAD + row * H;
    const y1 = y0 + H;
    const cy = y0 + H / 2;
    const top = cy - GAP_Y;
    const bottom = cy + GAP_Y;

    // Merge runs of full blocks into one rectangle each, so no hairline seams appear.
    for (let col = 0; col < chars.length;) {
      if (chars[col] !== "█") {
        col++;
        continue;
      }
      const start = col;
      while (chars[col] === "█") col++;
      // A little extra height hides the seam between rows.
      blocks.push(
        `<rect x="${PAD + start * W}" y="${y0}" width="${(col - start) * W}" height="${H + 0.5}"/>`,
      );
    }

    chars.forEach((char, col) => {
      const x0 = PAD + col * W;
      const x1 = x0 + W;
      const cx = x0 + W / 2;
      const left = cx - GAP_X;
      const right = cx + GAP_X;
      switch (char) {
        case "═":
          lines.push(`M${x0} ${top}H${x1}`, `M${x0} ${bottom}H${x1}`);
          break;
        case "║":
          lines.push(`M${left} ${y0}V${y1}`, `M${right} ${y0}V${y1}`);
          break;
        case "╔": // down and right
          lines.push(`M${x1} ${top}H${left}V${y1}`, `M${x1} ${bottom}H${right}V${y1}`);
          break;
        case "╗": // down and left
          lines.push(`M${x0} ${top}H${right}V${y1}`, `M${x0} ${bottom}H${left}V${y1}`);
          break;
        case "╚": // up and right
          lines.push(`M${left} ${y0}V${bottom}H${x1}`, `M${right} ${y0}V${top}H${x1}`);
          break;
        case "╝": // up and left
          lines.push(`M${right} ${y0}V${bottom}H${x0}`, `M${left} ${y0}V${top}H${x0}`);
          break;
        case " ":
        case "█":
          break;
        default:
          throw new Error(`No shape for ${JSON.stringify(char)} at row ${row}, column ${col}`);
      }
    });
  });

  const cols = Math.max(...art.map((line) => [...line].length));
  return {
    width: cols * W + PAD * 2,
    height: art.length * H + PAD * 2,
    shapes: (
      shadowClass,
    ) => `<path class="${shadowClass}" fill="none" stroke-width="1.4" stroke-linejoin="miter" d="${lines.join("")}"/>
    <g fill="url(#fill)">
      ${blocks.join("\n      ")}
    </g>`,
  };
}

const banner = draw(ART);
const logo = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${banner.width} ${banner.height}" width="${banner.width}" height="${banner.height}" role="img" aria-labelledby="title">
  <!-- Generated by scripts/gen-logo.mjs. Do not edit. -->
  <title id="title">Jesutobits</title>
  <defs>
    <linearGradient id="fill" gradientUnits="userSpaceOnUse" x1="${PAD}" y1="0" x2="${banner.width - PAD}" y2="0">${GRADIENT_STOPS}
    </linearGradient>
  </defs>
  <style>
    .shadow { stroke: #94A3B8; }
    @media (prefers-color-scheme: dark) {
      .shadow { stroke: #64748B; }
    }
  </style>
  <g>
    ${banner.shapes("shadow")}
  </g>
</svg>
`;

// The icon sits on its own dark tile, so it needs no dark-mode variant.
const j = draw(ART.map((line) => [...line].slice(0, J_COLUMNS).join("")));
const ICON = 512;
const scale = (ICON * 0.66) / j.height;
const offsetX = (ICON - j.width * scale) / 2;
const offsetY = (ICON - j.height * scale) / 2;
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${ICON} ${ICON}" width="${ICON}" height="${ICON}" role="img" aria-labelledby="title">
  <!-- Generated by scripts/gen-logo.mjs. Do not edit. -->
  <title id="title">Jesutobits</title>
  <defs>
    <linearGradient id="fill" gradientUnits="userSpaceOnUse" x1="${PAD}" y1="0" x2="${j.width - PAD}" y2="0">${GRADIENT_STOPS}
    </linearGradient>
  </defs>
  <rect width="${ICON}" height="${ICON}" rx="${ICON * 0.2}" fill="#0F172A"/>
  <g transform="translate(${offsetX.toFixed(2)} ${offsetY.toFixed(2)}) scale(${scale.toFixed(4)})" stroke="#64748B">
    ${j.shapes("shadow")}
  </g>
</svg>
`;

const assets = join(dirname(fileURLToPath(import.meta.url)), "..", "docs", "assets");
await writeFile(join(assets, "jesutobits-logo.svg"), logo, "utf8");
await writeFile(join(assets, "jesutobits-icon.svg"), icon, "utf8");
