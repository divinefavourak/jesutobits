// Draws the box-drawing logo (the banner in AGENTS.md) as an SVG of plain shapes, so it
// renders identically everywhere. As text, `█` and `═║╔╗╚╝` fall back to other fonts in
// many Markdown previews and lose their alignment.
// Output: docs/assets/jesutobits-logo.svg. Run: node scripts/gen-logo.mjs
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ART = [
  "     ██╗███████╗███████╗██╗   ██╗████████╗ ██████╗ ██████╗ ██╗████████╗███████╗",
  "     ██║██╔════╝██╔════╝██║   ██║╚══██╔══╝██╔═══██╗██╔══██╗██║╚══██╔══╝██╔════╝",
  "     ██║█████╗  ███████╗██║   ██║   ██║   ██║   ██║██████╔╝██║   ██║   ███████╗",
  "██   ██║██╔══╝  ╚════██║██║   ██║   ██║   ██║   ██║██╔══██╗██║   ██║   ╚════██║",
  "╚█████╔╝███████╗███████║╚██████╔╝   ██║   ╚██████╔╝██████╔╝██║   ██║   ███████║",
  " ╚════╝ ╚══════╝╚══════╝ ╚═════╝    ╚═╝    ╚═════╝ ╚═════╝ ╚═╝   ╚═╝   ╚══════╝",
];

// Terminal-like cell, twice as tall as wide. Double lines sit GAP_X / GAP_Y either side of
// the cell centre.
const W = 10;
const H = 20;
const GAP_X = 2;
const GAP_Y = 3;
const PAD = 10;

const cols = Math.max(...ART.map((line) => [...line].length));
const width = cols * W + PAD * 2;
const height = ART.length * H + PAD * 2;

const blocks = [];
const lines = [];

ART.forEach((line, row) => {
  const chars = [...line];
  const y0 = PAD + row * H;
  const y1 = y0 + H;
  const cy = y0 + H / 2;
  const top = cy - GAP_Y;
  const bottom = cy + GAP_Y;

  // Merge runs of full blocks into one rectangle each, so no hairline seams appear.
  for (let col = 0; col < chars.length;) {
    if (chars[col] !== "█") {
      col++;
      continue;
    }
    const start = col;
    while (chars[col] === "█") col++;
    // A little extra height hides the seam between rows.
    blocks.push(
      `<rect x="${PAD + start * W}" y="${y0}" width="${(col - start) * W}" height="${H + 0.5}"/>`,
    );
  }

  chars.forEach((char, col) => {
    const x0 = PAD + col * W;
    const x1 = x0 + W;
    const cx = x0 + W / 2;
    const left = cx - GAP_X;
    const right = cx + GAP_X;
    switch (char) {
      case "═":
        lines.push(`M${x0} ${top}H${x1}`, `M${x0} ${bottom}H${x1}`);
        break;
      case "║":
        lines.push(`M${left} ${y0}V${y1}`, `M${right} ${y0}V${y1}`);
        break;
      case "╔": // down and right
        lines.push(`M${x1} ${top}H${left}V${y1}`, `M${x1} ${bottom}H${right}V${y1}`);
        break;
      case "╗": // down and left
        lines.push(`M${x0} ${top}H${right}V${y1}`, `M${x0} ${bottom}H${left}V${y1}`);
        break;
      case "╚": // up and right
        lines.push(`M${left} ${y0}V${bottom}H${x1}`, `M${right} ${y0}V${top}H${x1}`);
        break;
      case "╝": // up and left
        lines.push(`M${right} ${y0}V${bottom}H${x0}`, `M${left} ${y0}V${top}H${x0}`);
        break;
      case " ":
      case "█":
        break;
      default:
        throw new Error(`No shape for ${JSON.stringify(char)} at row ${row}, column ${col}`);
    }
  });
});

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-labelledby="title">
  <!-- Generated by scripts/gen-logo.mjs. Do not edit. -->
  <title id="title">Jesutobits</title>
  <defs>
    <linearGradient id="fill" gradientUnits="userSpaceOnUse" x1="${PAD}" y1="0" x2="${width - PAD}" y2="0">
      <stop offset="0" stop-color="#4F46E5"/>
      <stop offset="0.5" stop-color="#6366F1"/>
      <stop offset="1" stop-color="#9333EA"/>
    </linearGradient>
  </defs>
  <style>
    .shadow { stroke: #94A3B8; }
    @media (prefers-color-scheme: dark) {
      .shadow { stroke: #64748B; }
    }
  </style>
  <path class="shadow" fill="none" stroke-width="1.4" stroke-linejoin="miter" d="${lines.join("")}"/>
  <g fill="url(#fill)">
    ${blocks.join("\n    ")}
  </g>
</svg>
`;

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "docs",
  "assets",
  "jesutobits-logo.svg",
);
await writeFile(out, svg, "utf8");
