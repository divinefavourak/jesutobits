// Generates the Host's method allowlist (ADR-0003, decision 3) from
// packages/protocol/generated/methods.json:
//   apps/desktop/src-tauri/src/rpc_relay/allowlist.rs
// Checked in, because the Rust build needs it before any JavaScript codegen can run.
// Run through `pnpm gen`, after gen-protocol.mjs.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const methods = JSON.parse(
  await readFile(join(root, "packages", "protocol", "generated", "methods.json"), "utf8"),
);

const list = (names) => names.map((name) => `    ${JSON.stringify(name)},`).join("\n");

const rust = `// Generated by scripts/gen-allowlist.mjs. Do not edit.
// Source: packages/protocol/generated/methods.json

/// Protocol version the Host sends in \`runtime.initialize\`.
pub const PROTOCOL_VERSION: &str = ${JSON.stringify(methods.protocolVersion)};

/// Runtime methods the Workbench may call through the relay. Anything else is rejected.
pub const WORKBENCH_METHODS: &[&str] = &[
${list(methods.workbench)}
];

/// Runtime methods the Host itself sends.
pub const HOST_METHODS: &[&str] = &[
${list(methods.host)}
];

/// Methods the runtime may call on the Host (reverse calls, ADR-0014).
pub const REVERSE_METHODS: &[&str] = &[
${list(methods.reverse)}
];

pub fn is_workbench_method(method: &str) -> bool {
    WORKBENCH_METHODS.contains(&method)
}

pub fn is_reverse_method(method: &str) -> bool {
    REVERSE_METHODS.contains(&method)
}
`;

await writeFile(
  join(root, "apps", "desktop", "src-tauri", "src", "rpc_relay", "allowlist.rs"),
  rust,
  "utf8",
);
